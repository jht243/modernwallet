// Templates the audited drafts into the site's stores (mindmap-pass 2026-10-25).
// Run: node reports/mindmap-pass/2026-10-25/template.mjs
// - writes src/data/spokes-checklists.ts (8 spokes) from drafts/<slug>.json
// - inserts/replaces the "checklists" hub entry in src/data/calculators.ts from drafts/checklists-hub.json
import fs from "fs";
import * as L from "../../../src/lib/checklists.ts";

const R = new URL("./", import.meta.url);
const read = (p) => JSON.parse(fs.readFileSync(new URL(p, R), "utf8"));
const rows = read("prompts/rows.json");
const vols = read("../cache/2026-10-25.checklists.volumes.json");
const UPDATED = "2026-10-26";

const KW = {
  "home-buying-checklist": "home buying checklist",
  "home-selling-checklist": "home selling checklist",
  "renting-checklist": "rental checklist",
  "landlord-checklist": "landlord checklist",
  "home-inspection-checklist": "home inspection checklist",
  "final-walkthrough-checklist": "final walkthrough checklist",
  "move-in-move-out-checklist": "move in checklist",
  "first-apartment-checklist": "first apartment checklist",
};
const RELATED = {
  "home-buying-checklist": ["home-inspection-checklist", "final-walkthrough-checklist", "home-selling-checklist"],
  "home-selling-checklist": ["home-buying-checklist", "final-walkthrough-checklist", "landlord-checklist"],
  "renting-checklist": ["move-in-move-out-checklist", "first-apartment-checklist", "landlord-checklist"],
  "landlord-checklist": ["move-in-move-out-checklist", "renting-checklist", "home-selling-checklist"],
  "home-inspection-checklist": ["home-buying-checklist", "final-walkthrough-checklist", "home-selling-checklist"],
  "final-walkthrough-checklist": ["home-buying-checklist", "home-inspection-checklist", "move-in-move-out-checklist"],
  "move-in-move-out-checklist": ["renting-checklist", "landlord-checklist", "first-apartment-checklist"],
  "first-apartment-checklist": ["renting-checklist", "move-in-move-out-checklist", "landlord-checklist"],
};

// Sources = every source the checklist's own items cite (plus the HUD tenant-rights page for the
// condition report, whose items are room rows rather than rule items).
function sourcesFor(cid) {
  const keys = new Set();
  for (const s of L.SECTIONS[cid] ?? []) for (const it of s.items) if (it.src) keys.add(it.src);
  if (cid === "move-in-move-out") for (const it of L.MOVE_IN_TIPS) if (it.src) keys.add(it.src);
  return [...keys].map((k) => L.SOURCES[k]);
}

const spokes = rows.map((r) => {
  const d = read(`drafts/${r.slug}.json`);
  const v = vols[KW[r.slug]] ?? {};
  return {
    calculator: "checklists",
    slug: r.slug,
    updated: UPDATED,
    title: d.title,
    metaDescription: d.metaDescription,
    targetKeyword: KW[r.slug],
    ...(v.volume ? { estimatedVolume: v.volume } : {}),
    ...(v.kd != null ? { estimatedKD: v.kd } : {}),
    h1: d.h1,
    introText: d.introText,
    toolHeading: d.toolHeading,
    toolSubheading: d.toolSubheading,
    howItWorks: d.howItWorks,
    workedExample: d.workedExample,
    commonMistakes: d.commonMistakes,
    faqs: d.faqs,
    sources: sourcesFor(r.cid),
    preset: { checklist: r.cid },
    relatedSlugs: RELATED[r.slug],
  };
});

const ts = `import type { SpokeEntry } from "./types";

// Checklist spokes (mindmap-pass 2026-10-25). One rule-driven island (src/components/ChecklistBuilder.tsx,
// rules in src/lib/checklists.ts) serves every page; preset.checklist picks which list it builds.
// Prose generated via scripts/lib/content_gen.py — drafts, meta and audit in reports/mindmap-pass/2026-10-25/.
// Generated by reports/mindmap-pass/2026-10-25/template.mjs; edit prose through the generator, not by hand.

export const CHECKLIST_SPOKES: SpokeEntry[] = ${JSON.stringify(spokes, null, 2)};
`;
fs.writeFileSync(new URL("../../../src/data/spokes-checklists.ts", R), ts);

// Hub entry
const h = read("drafts/checklists-hub.json");
const calcPath = new URL("../../../src/data/calculators.ts", R);
let calc = fs.readFileSync(calcPath, "utf8");
const START = "  // Checklists hub — mindmap-pass (2026-10-25).";
const END = "  // /Checklists hub";
const hub = {
  id: "checklists",
  islandId: "checklists",
  label: "Checklists",
  navOrder: 63,
  metaTitle: h.metaTitle,
  metaDescription: h.metaDescription,
  targetKeyword: "house checklist",
  h1: h.h1,
  introText: h.introText,
  howItWorks: h.howItWorks,
  faqs: h.faqs,
  sources: [L.SOURCES.lead, L.SOURCES.cd, L.SOURCES.flood, L.SOURCES.ashi],
  updated: UPDATED,
  defaultPreset: { checklist: "home-buying", picker: true },
};
const block = `${START} Prose generated via scripts/lib/content_gen.py\n  // (reports/mindmap-pass/2026-10-25/drafts/checklists-hub.json). Spokes live in spokes-checklists.ts.\n  ${JSON.stringify(hub, null, 2).replace(/\n/g, "\n  ")},\n${END}\n`;
if (calc.includes(START)) calc = calc.slice(0, calc.indexOf(START)) + block + calc.slice(calc.indexOf(END) + END.length + 1);
else calc = calc.replace(/\n\];\n\nexport const CALC_BY_ID/, `\n${block}];\n\nexport const CALC_BY_ID`);
fs.writeFileSync(calcPath, calc);
console.log("templated", spokes.length, "spokes + hub");
